import { readFileSync } from 'node:fs';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { readMessage } from '../public/js/reader/read.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const fixtures = JSON.parse(
  readFileSync(path.join(root, 'tests', 'fixtures', 'messages.json'), 'utf8'),
);

const STYLES = ['en', 'te-script', 'hi-script', 'te-latin', 'hi-latin', 'mixed'];

const rows = new Map(STYLES.map((s) => [s, { messages: 0, stated: 0, correct: 0, wrong: 0, invented: 0 }]));

for (const entry of fixtures) {
  const row = rows.get(entry.style) ?? { messages: 0, stated: 0, correct: 0, wrong: 0, invented: 0 };
  rows.set(entry.style, row);
  row.messages += 1;

  const result = readMessage(entry.text);

  for (const [field, want] of Object.entries(entry.expected)) {
    row.stated += 1;
    if (field === 'warnings') {
      const ok = want.every((code) => result.warnings.includes(code));
      if (ok) row.correct += 1;
      else row.wrong += 1;
      continue;
    }
    if (result.profile[field] === want) row.correct += 1;
    else row.wrong += 1;
  }

  for (const field of entry.must_not) {
    if (result.profile[field] !== undefined) row.invented += 1;
  }
}

const header = [
  '| Style | Messages | Stated details | Correct | Wrong | Invented |',
  '|---|---:|---:|---:|---:|---:|',
];
const body = [];
const totals = { messages: 0, stated: 0, correct: 0, wrong: 0, invented: 0 };
for (const [style, r] of rows) {
  body.push(`| ${style} | ${r.messages} | ${r.stated} | ${r.correct} | ${r.wrong} | ${r.invented} |`);
  for (const k of Object.keys(totals)) totals[k] += r[k];
}
body.push(
  `| **total** | ${totals.messages} | ${totals.stated} | ${totals.correct} | ${totals.wrong} | ${totals.invented} |`,
);

const output = [
  '# Prapti reader accuracy',
  '',
  'Generated by `scripts/accuracy.js` from `tests/fixtures/messages.json`.',
  '',
  'Correct: stated detail read exactly. Wrong: stated detail missing or different.',
  'Invented: a field the text does not state (listed in must_not) was set anyway.',
  '',
  ...header,
  ...body,
  '',
].join('\n');

console.log(output);

const docsDir = path.join(root, 'docs');
await mkdir(docsDir, { recursive: true });
await writeFile(path.join(docsDir, 'accuracy.md'), output, 'utf8');
console.log(`Wrote ${path.join(docsDir, 'accuracy.md')}`);
